from pydantic import BaseModel, Field
from typing import List, Optional

class TripRequest(BaseModel):
    """
    Trip creation request payload matching the 3-step React frontend wizard.
    Accepts ANY custom destination globally (e.g. Manali, Goa, Bali, Paris, Tokyo, etc.)
    without requiring membership in a hardcoded list.
    """
    destination: str = Field(
        ...,
        min_length=1,
        max_length=200,
        description="Custom destination name (e.g. Manali, Goa, Bali, Spiti Valley, etc.)"
    )
    startDate: str = Field(..., description="Departure date in YYYY-MM-DD")
    endDate: str = Field(..., description="Return date in YYYY-MM-DD")
    durationDays: int = Field(..., ge=1, le=60, description="Duration in days")
    budget: str = Field("moderate", description="Budget level: budget, moderate, or luxury")
    travelerType: str = Field("couple", description="Traveler category: solo, couple, family, friends")
    travelersCount: int = Field(2, ge=1, le=50, description="Total count of travelers")
    interests: List[str] = Field(default_factory=list, description="Travel interests list")
    pace: str = Field("balanced", description="Pace: relaxed, balanced, packed")
    language: str = Field("en", description="Language code: en, hi, es, fr")
    languageName: Optional[str] = Field(None, description="Human readable language name")

    model_config = {
        "json_schema_extra": {
            "example": {
                "destination": "Manali",
                "startDate": "2026-06-01",
                "endDate": "2026-06-05",
                "durationDays": 4,
                "budget": "moderate",
                "travelerType": "couple",
                "travelersCount": 2,
                "interests": ["nature", "adventure", "culture"],
                "pace": "balanced",
                "language": "en",
                "languageName": "English"
            }
        }
    }


class DayActivity(BaseModel):
    """Individual activity planned during a day."""
    time_of_day: str = Field(..., description="Timing: Morning, Afternoon, or Evening")
    title: str = Field(..., description="Descriptive activity title")
    description: str = Field(..., description="Detailed description of the recommendation")
    photo_query: str = Field(..., description="Search keyword for finding relevant photography")
    estimated_cost: Optional[str] = Field(None, description="Estimated expense (e.g. '$15 - $25 per person')")
    location: Optional[str] = Field(None, description="Specific landmark, district, or neighborhood name")
    attraction: Optional[str] = Field(None, description="Key attraction, landmark or cultural point")
    food_option: Optional[str] = Field(None, description="Recommended food, dish, or dining venue")


class DayPlan(BaseModel):
    """Daily itinerary plan containing structured activities."""
    day_number: int = Field(..., description="Sequential day number (1-based)")
    theme: str = Field(..., description="Theme for the day, e.g. 'Old Town Charm & Heritage'")
    activities: List[DayActivity] = Field(default_factory=list, description="Morning, afternoon, and evening activities")


class BudgetBreakdown(BaseModel):
    """Categorized estimated expenditure."""
    accommodation: Optional[str] = Field(None, description="Estimated lodging expense")
    food_and_dining: Optional[str] = Field(None, description="Estimated meals and beverages")
    activities_and_entry: Optional[str] = Field(None, description="Estimated sightseeing & ticket fees")
    local_transport: Optional[str] = Field(None, description="Estimated local transit & taxi fares")


class TripResponse(BaseModel):
    """
    Structured trip itinerary response.
    Explicitly indicates whether it is generated by live Groq AI or by the mock generator.
    """
    id: Optional[str] = Field(None, description="Unique UUID identifier for saved trips")
    created_at: Optional[str] = Field(None, description="ISO timestamp of creation")
    destination: str
    summary: str
    duration_days: int
    start_date: Optional[str] = None
    end_date: Optional[str] = None
    language: str = "en"
    budget_tier: str = "moderate"
    currency: str = "USD"
    estimated_total_cost: Optional[str] = None
    budget_breakdown: Optional[BudgetBreakdown] = None
    travel_tips: List[str] = Field(default_factory=list, description="Practical travel etiquette and packing tips")
    transport_suggestions: List[str] = Field(default_factory=list, description="Local transport advice and commuting tips")
    accommodation_suggestions: List[str] = Field(default_factory=list, description="Curated hotel, hostel, or resort options matching budget tier")
    disclaimer: Optional[str] = Field(
        default="Prices, opening hours, and transport schedules are estimates based on standard regional rates and may vary seasonally. Real-time availability must be verified directly with providers. Live bookings are not confirmed.",
        description="Official disclaimer on estimates vs live bookings"
    )
    travelers_count: int = 1
    traveler_type: str = "solo"
    pace: str = "balanced"
    interests: List[str] = Field(default_factory=list)
    days: List[DayPlan] = Field(default_factory=list)
    hero_image_url: Optional[str] = None
    is_mock: bool = Field(False, description="True if generated by local fallback, False if live Groq AI")
    source: str = Field("groq_ai", description="Origin of generation: 'groq_ai' or 'mock_generator'")


class RegenerateDayRequest(BaseModel):
    """Request payload to regenerate a single day plan."""
    destination: str
    day_number: int = Field(..., ge=1, le=60, description="Day number to regenerate")
    current_theme: Optional[str] = None
    interests: List[str] = Field(default_factory=list)
    budget: str = "moderate"
    travelerType: str = "couple"
    pace: str = "balanced"
    language: str = "en"
    custom_instruction: Optional[str] = Field(None, description="Optional user prompt (e.g. 'more nature hikes', 'budget street food')")


class TripSaveRequest(BaseModel):
    """Request to persist an itinerary in database."""
    trip: TripResponse
    user_id: Optional[str] = "local-guest"


class TripRecord(BaseModel):
    """Saved trip record representation."""
    id: str
    user_id: str
    destination: str
    duration_days: int
    created_at: str
    itinerary_data: TripResponse


class TripListResponse(BaseModel):
    """List of saved itineraries."""
    trips: List[TripRecord]
    total: int


class DestinationSearchResult(BaseModel):
    """Worldwide geographic destination search result item."""
    name: str = Field(..., description="Place, city, or country name")
    region: Optional[str] = Field("", description="State, province, or administrative division")
    country: str = Field(..., description="Country name")
    country_code: Optional[str] = Field("", description="ISO 2-letter country code")
    full_name: str = Field(..., description="Full formatted name (e.g. 'Paris, Île-de-France, France')")
    place_type: str = Field("city", description="Type: city, country, region, or destination")
    population: Optional[int] = Field(0, description="Estimated population")
    latitude: Optional[float] = Field(0.0)
    longitude: Optional[float] = Field(0.0)


class DestinationSearchResponse(BaseModel):
    """Response payload for worldwide destination search."""
    query: str
    total: int
    results: List[DestinationSearchResult] = Field(default_factory=list)
